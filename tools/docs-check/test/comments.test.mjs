// The scanner of comments: what it reads as a comment, and what it leaves as code or a string.

import { test } from "node:test";
import assert from "node:assert/strict";
import { commentKind, commentsOf, isGenerated } from "../comments.mjs";

const texts = (source, kind = "js") => commentsOf(source, kind).map((c) => c.text);

test("which files have comments it reads", () => {
  for (const file of ["a.ts", "b/a.tsx", "a.mts", "a.cts", "a.js", "a.jsx", "a.mjs", "a.cjs"]) assert.equal(commentKind(file), "js", file);
  for (const file of ["a.go", "a/b.proto", "a.jsonc", ".devcontainer/devcontainer.json"]) assert.equal(commentKind(file), "c", file);
  for (const file of ["a.sh", "a.yml", ".github/a.yaml", "justfile", "x/.justfile", "Dockerfile", ".devcontainer/Dockerfile", "Dockerfile.dev", "kinds/typescript.Dockerfile"]) {
    assert.equal(commentKind(file), "hash", file);
  }
  for (const file of ["tofu/a.tf", "a.tofu", "a.tfvars", "tofu/backend.hcl", "tofu/tests/a.tftest.hcl"]) assert.equal(commentKind(file), "hcl", file);
  for (const file of ["a.md", "a.json", "a.html", "Dockerfiles/a.txt", "tofu/.terraform.lock.hcl"]) assert.equal(commentKind(file), null, file);
});

test("generated code is known by its mark, a line of its own in the first lines", () => {
  assert.ok(isGenerated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n"));
  assert.ok(isGenerated('// License.\n\n// @generated by protoc-gen-es v2.17.0\n'));
  assert.ok(!isGenerated("// Code we wrote.\n"));
  // A mark quoted in a comment or a string is not one.
  assert.ok(!isGenerated('// Its first lines say "Code generated … DO NOT EDIT" or "@generated".\n'));
  assert.ok(!isGenerated('const HEADER = "// Code generated by x; DO NOT EDIT.";\n'));
  assert.ok(!isGenerated(`${"\n".repeat(30)}// Code generated by x. DO NOT EDIT.\n`));
});

test("line and block comments, a run of line comments as one", () => {
  const comments = commentsOf("const a = 1; // one\n// two\n\n// three\n/* four\n * five */ x();\n", "slash");
  assert.deepEqual(
    comments.map((c) => c.text),
    [" one\n two", " three", " four\n  five "],
  );
  assert.equal(comments[0].lineAt(0), 1);
  assert.equal(comments[0].lineAt(" one\n t".length), 2);
  assert.equal(comments[2].lineAt(" four\n  ".length), 6);
});

test("strings are not comments", () => {
  assert.deepEqual(texts(`const a = "// no"; const b = 'R1 // no'; // yes\n`), [" yes"]);
  assert.deepEqual(texts(`const a = "a \\" // no"; // yes\n`), [" yes"]);
  assert.deepEqual(texts(`const a = "unterminated\nb(); // yes\n`), [" yes"]);
});

test("template literals and their ${}, nested, are not comments", () => {
  assert.deepEqual(texts("const a = `// no ${b ? `// no ${c}` : { d: 1 }.d} \\` // no`; // yes\n"), [" yes"]);
  assert.deepEqual(texts("const a = `${f({ x: 1 })} /* no */`; /* yes */\n"), [" yes "]);
});

test("a literal of a regular expression is not a comment, a division is", () => {
  assert.deepEqual(texts("const a = /\\/\\/ no [/]/g; // yes\n"), [" yes"]);
  assert.deepEqual(texts("if (x) return /no\\//.test(y); // yes\n"), [" yes"]);
  assert.deepEqual(texts("const a = b / c; // yes\nconst d = (e) / 2 /* yes */;\n"), [" yes", " yes "]);
  // A `/` with no closing one on its line is a division after all.
  assert.deepEqual(texts("x = [/b\n]; // yes\n"), [" yes"]);
  assert.deepEqual(texts('let x = a++ / 2; // yes\nlet y = b-- / "q"; // yes\n'), [" yes\n yes"]);
});

test("Go: a raw string spans lines, a rune is not a quote, no literals of regular expressions", () => {
  const go = "var a = `// no\n// no` // yes\nvar b = '\\'' // yes\nvar c = d / e // yes\n";
  assert.deepEqual(texts(go, "c"), [" yes\n yes\n yes"]);
});

test("an unclosed block comment runs to the end", () => {
  assert.deepEqual(texts("a(); /* open\nstill"), [" open\nstill"]);
});

test("# comments: at a line's start or after a space, outside its quotes", () => {
  const yaml = [
    "# one",
    "  key: value # two",
    'name: "a # no" # three',
    "url: https://x.org/#no",
    "msg: don't # four",
    "run: echo ${#a} $# 'it # no'",
    "say: 'a \"q\" # no' # five",
    'esc: "a \\" # no" # six',
  ].join("\n");
  assert.deepEqual(texts(yaml, "hash"), [" one\n two\n three", " four", " five\n six"]);
  const more = ["key: 'it''s # no' # one", 'run: echo ${x:-"a # no"} # two'].join("\n");
  assert.deepEqual(texts(more, "hash"), [" one\n two"]);
});

test("HCL: `#`, `//` and `/* */`, outside strings and heredocs", () => {
  const hcl = [
    "# one",
    'resource "a" "b" { # two',
    '  name = "x # no // no /* no */" // three',
    "  url  = \"https://x.org/#no\"",
    '  msg  = "don\'t \\" # no" /* four */ # five',
    "  /* six",
    "   * seven */ x = 1 # eight",
    "  policy = <<-EOT",
    "    # no",
    "    EOT",
    "}",
    "/* nine */",
  ].join("\n");
  assert.deepEqual(texts(hcl, "hcl"), [" one\n two\n three", " four ", " five", " six\n  seven ", " eight", " nine "]);
  // A comment left open runs to the end of the file.
  assert.deepEqual(texts("x = 1\n/* one\ntwo", "hcl"), [" one\ntwo"]);
  // No space is needed before a comment, and the code of a template in a string may span lines.
  assert.deepEqual(texts('x = 1# one\ny = "a"// two\nz = {/* three */}', "hcl"), [" one\n two", " three "]);
  const template = ['a = "${', '  b ? "# no" : "c"', '}" # one', 'd = "%{ if e }# no%{ endif }" # two', 'f = "g # no'].join("\n");
  assert.deepEqual(texts(template, "hcl"), [" one\n two"]);
});

test("the body of a heredoc is text, not comments", () => {
  const shell = [
    "cat <<'EOF' >> \"$GITHUB_STEP_SUMMARY\" # one",
    "## R5 is a heading",
    "EOF",
    "# two",
    "  run: |",
    "    cat <<-END",
    "    # no",
    "    END",
    "    x=$((1<<2)) # three",
    "    cat <<< \"# no\" # four",
  ].join("\n");
  assert.deepEqual(texts(shell, "hash"), [" one", " two", " three\n four"]);
});
