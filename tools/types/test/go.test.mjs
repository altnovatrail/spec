const here = path.dirname(fileURLToPath(import.meta.url));
const spec = path.join(here, "..", "..", "..");

const struct = (name, schema, fields, extra = {}) => ({ name, schema, pointer: extra.pointer ?? "", doc: extra.doc ?? "", kind: "struct", fields });
const fieldOf = (json, type, extra = {}) => ({ json, doc: "", default: undefined, required: false, open: false, type, ...extra });

// A model of a part, an enumeration, an ID, a map and another name of a struct.
function smallModel() {
  const types = new Map();
  const add = (type) => types.set(type.name, type);
  add(
    struct(
      "Part",
      "part.schema.json",
      [
        fieldOf("id", { named: "PartID" }, { required: true, open: true, doc: "Its ID." }),
        fieldOf("kind", { named: "PartKind" }, { required: true, open: true }),
        fieldOf("step", { primitive: "integer" }, { default: 50, open: true }),
        fieldOf("pieces", { list: { named: "Piece" } }, { open: true }),
        fieldOf("tiers", { named: "Tiers" }),
        fieldOf("note", { nullable: { primitive: "string" } }, { required: true, open: true }),
        fieldOf("other", { named: "OtherPiece" }),
        fieldOf("shelf", { named: "Shelf" }, { open: true }),
      ],
      { doc: "A part." },
    ),
  );
  add({ name: "PartID", schema: "common.schema.json", pointer: "/$defs/part_id", doc: "", kind: "named", type: { named: "LocalID" } });
  add({ name: "LocalID", schema: "common.schema.json", pointer: "/$defs/local_id", doc: "", kind: "string", values: null });
  add({ name: "PartKind", schema: "part.schema.json", pointer: "/properties/kind", doc: "", kind: "string", values: ["handwriting_sheet", "module-index.one"] });
  add({ name: "Grade", schema: "common.schema.json", pointer: "/$defs/grade", doc: "", kind: "integer" });
  add({ name: "Tiers", schema: "part.schema.json", pointer: "/$defs/tiers", doc: "", kind: "named", type: { map: { key: { named: "PartID" }, value: { primitive: "integer" } } } });
  add(struct("Piece", "part.schema.json", [fieldOf("size", { primitive: "number" }, { required: true }), fieldOf("on", { primitive: "boolean" })], { pointer: "/$defs/piece" }));
  add({ name: "OtherPiece", schema: "part.schema.json", pointer: "/$defs/other_piece", doc: "", kind: "named", type: { named: "Piece" } });
  add({ name: "Shelf", schema: "part.schema.json", pointer: "/$defs/shelf", doc: "", kind: "named", type: { map: { key: { named: "PartID" }, value: { named: "OtherPiece" }, open: true } } });
  add(struct("Empty", "empty.schema.json", [fieldOf("hidden", { primitive: "string" })]));
  const open = new Map([
    ["Part", { name: "Part", fields: types.get("Part").fields.filter((field) => field.open) }],
    ["Piece", { name: "Piece", fields: [] }],
    ["Empty", { name: "Empty", fields: [] }],
  ]);
  return { types, roots: new Map([["part", "Part"], ["empty", "Empty"]]), open };
}

test("a struct's field is a value when the object always holds it, and a pointer, a slice or a map with omitzero otherwise", () => {
  const files = goFiles(smallModel(), "0.1");
  const part = files.get(`${TYPES_DIR}/part.go`);
  assert.match(part, /^\/\/ Code generated by tools\/types from format\/schemas; DO NOT EDIT\.\n\npackage formatv0\n/);
  assert.match(part, /\/\/ Part is the type of part\.schema\.json\.\n\/\/\n\/\/ A part\.\ntype Part struct \{\n/);
  assert.match(part, /\t\/\/ Its ID\.\n\tID PartID `json:"id"`\n/);
  assert.match(part, /\tKind PartKind `json:"kind"`\n/);
  assert.match(part, /\t\/\/ Default: 50\.\n\tStep \*int64 `json:"step,omitzero"`\n/);
  assert.match(part, /\tPieces \[\]Piece `json:"pieces,omitzero"`\n/);
  assert.match(part, /\tTiers Tiers `json:"tiers,omitzero"`\n/);
  assert.match(part, /\tNote \*string `json:"note"`\n/);
  assert.match(part, /\tOther \*OtherPiece `json:"other,omitzero"`\n/);
  assert.match(part, /\tSize float64 `json:"size"`\n\tOn \*bool `json:"on,omitzero"`\n/);
  // An enumeration's values are constants; another name of a struct is the struct; a string, an
  // integer and a map under a name of their own are types of their own.
  assert.match(part, /const \(\n\tPartKindHandwritingSheet PartKind = "handwriting_sheet"\n\tPartKindModuleIndexOne PartKind = "module-index\.one"\n\)/);
  assert.match(part, /type OtherPiece = Piece\n/);
  assert.match(part, /type Tiers map\[PartID\]int64\n/);
  const common = files.get(`${TYPES_DIR}/common.go`);
  assert.match(common, /type PartID LocalID\n/);
  assert.match(common, /type LocalID string\n/);
  assert.match(common, /type Grade int64\n/);
  assert.match(files.get(`${TYPES_DIR}/doc.go`), /version 0\.1 in format\/schemas[^]*\npackage formatv0\n$/);
});

test("an open view holds its open fields, by the open views of structs and formatv0's other types", () => {
  const files = goFiles(smallModel(), "0.1");
  const part = files.get(`${OPEN_DIR}/part.go`);
  assert.match(part, /^\/\/ Code generated by tools\/types from format\/schemas; DO NOT EDIT\.\n\npackage open\n\nimport "github\.com\/altnovatrail\/spec\/types\/formatv0"\n/);
  assert.match(part, /\/\/ Part is the open view of formatv0\.Part, the type of part\.schema\.json: its fields marked x-open\.\n/);
  assert.match(part, /\tID formatv0\.PartID `json:"id"`\n\tKind formatv0\.PartKind `json:"kind"`\n/);
  assert.match(part, /\tPieces \[\]Piece `json:"pieces,omitzero"`\n\tNote \*string `json:"note"`\n/);
  // A map of structs under a name of its own is written out, of their open views.
  assert.match(part, /\tShelf map\[formatv0\.PartID\]Piece `json:"shelf,omitzero"`\n\}/);
  assert.match(part, /type Piece struct\{\}\n/);
  // A file whose views use nothing of formatv0 imports nothing.
  assert.equal(files.get(`${OPEN_DIR}/empty.go`).includes("import"), false);
  assert.match(files.get(`${OPEN_DIR}/doc.go`), /\npackage open\n$/);
  const registry = files.get(REGISTRY);
  assert.match(registry, /\t"formatv0\.Empty": func\(\) any \{ return new\(formatv0\.Empty\) \},\n\t"formatv0\.Part": /);
  assert.match(registry, /\t"open\.Part": func\(\) any \{ return new\(open\.Part\) \},\n/);
});

test("what the Go of the model cannot hold stops it", () => {
  const nullable = smallModel();
  nullable.types.get("Part").fields.push(fieldOf("maybe", { nullable: { primitive: "string" } }));
  assert.throws(() => goFiles(nullable, "0.1"), /the field maybe may be left out and may be null/);
  const asType = smallModel();
  asType.types.set("PartKindModuleIndexOne", { name: "PartKindModuleIndexOne", schema: "part.schema.json", pointer: "/$defs/x", doc: "", kind: "integer" });
  assert.throws(() => goFiles(asType, "0.1"), /the constant PartKindModuleIndexOne of PartKind is named as a type is/);
  const twice = smallModel();
  twice.types.set("PartKindModule", { name: "PartKindModule", schema: "part.schema.json", pointer: "/$defs/y", doc: "", kind: "string", values: ["index.one"] });
  assert.throws(() => goFiles(twice, "0.1"), /the constant PartKindModuleIndexOne of PartKindModule is named as one of PartKind is/);
});

test("names and comments", () => {
  const words = Array.from({ length: 40 }, (_, index) => `word${index}`).join(" ");
  const comment = commentOf(`${words}\n\nA second paragraph.`, "\t");
  const lines = comment.split("\n").filter(Boolean);
  assert.ok(lines.every((line) => line.startsWith("\t//") && line.length - 1 + 4 <= 100), comment);
  assert.ok(lines.includes("\t//"));
  assert.equal(lines.at(-1), "\t// A second paragraph.");
});

test("spec's own format gives its types, which are the files in the repository", () => {
  const { model, files } = generate(spec);
  assert.equal(model.roots.get("task"), "Task");
  assert.deepEqual(
    model.open.get("Task").fields.map((field) => field.json),
    ["id", "statement", "canvas", "items", "givens", "unknown"],
  );
  for (const file of files.keys()) assert.ok(fs.existsSync(path.join(spec, file)), `${file} is not in the repository: run just types`);
  const { parts, version } = readFormat(spec);
  assert.equal(version, fs.readFileSync(path.join(spec, "format/VERSION"), "utf8").trim());
  assert.deepEqual([...parts].sort(), ["lesson", "manifest", "skill-graph", "solving-steps", "task", "techniques", "traps"]);
});

test("the generator writes its files into a new folder, and refuses to write over one", () => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), "types-"));
  const script = path.join(spec, "tools", "types", "main.mjs");
  const written = spawnSync(process.execPath, [script, folder], { encoding: "utf8" });
  assert.equal(written.status, 0, written.stderr);
  assert.ok(fs.existsSync(path.join(folder, TYPES_DIR, "task.go")));
  assert.ok(fs.existsSync(path.join(folder, OPEN_DIR, "task.go")));
  assert.ok(fs.existsSync(path.join(folder, REGISTRY)));
  const again = spawnSync(process.execPath, [script, folder], { encoding: "utf8" });
  assert.equal(again.status, 1);
  assert.match(again.stderr, /^types: EEXIST/);
  assert.throws(() => writeFiles(new Map([["a.go", ""]]), path.join(folder, REGISTRY)), /ENOTDIR|EEXIST/);
  const usage = spawnSync(process.execPath, [script], { encoding: "utf8" });
  assert.equal(usage.status, 2);
  assert.match(usage.stderr, /^usage: node tools\/types\/main\.mjs <folder>/);
});

test("the corpus holds every value of format/ that passes a schema, and its open views", () => {
  const { schemas, parts } = readFormat(spec);
  const { cases, problems } = corpusOf(spec, buildModel(schemas, parts));
  assert.deepEqual(problems, []);
  const types = new Set(cases.map((each) => each.type));
  for (const name of ["Manifest", "SkillGraph", "Traps", "Techniques", "SolvingSteps", "Task", "Lesson", "CanonicalView", "Inventory", "ModuleIndex", "VerdictVector", "LeakVector", "RandomVector", "TemplateVector", "TierVector", "PackageVector", "IndexVector"]) {
    assert.ok(types.has(`formatv0.${name}`), name);
  }
  for (const name of ["Manifest", "SkillGraph", "Traps", "Techniques", "SolvingSteps", "Task", "Lesson"]) assert.ok(types.has(`open.${name}`), name);
  // The part of a vector of the open view with a closed field is a closed case; a part with none
  // is not.
  assert.ok(cases.some((each) => each.closed && each.type === "open.Task"));
  assert.ok(cases.some((each) => !each.closed && each.type === "open.Manifest" && each.file.endsWith("/part.yaml")));
  assert.ok(cases.some((each) => each.file.endsWith("(its canonical view)")));
});

test("the corpus names what it cannot take", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "types-corpus-"));
  fs.cpSync(path.join(spec, "format"), path.join(root, "format"), { recursive: true });
  const { schemas, parts } = readFormat(root);
  const model = buildModel(schemas, parts);
  fs.mkdirSync(path.join(root, "format/vectors/unknown"));
  const task = fs.readdirSync(path.join(root, "format/examples/task/valid"))[0];
  fs.writeFileSync(path.join(root, "format/examples/task/valid", task), "id: [\n");
  fs.writeFileSync(path.join(root, "format/examples/manifest/valid/extra.yaml"), "id: a\n");
  fs.writeFileSync(path.join(root, "format/examples/manifest/valid/rule.yaml"), "a: 1\n");
  const module = fs.readdirSync(path.join(root, "format/examples/module/valid"))[0];
  fs.writeFileSync(path.join(root, "format/examples/module/valid", module, "skill-graph.yaml"), "skills:\n  a:\n    title: A\n    assessability: none\n    prerequisites: [b]\n");
  fs.mkdirSync(path.join(root, "format/examples/nothing/valid"), { recursive: true });
  fs.writeFileSync(path.join(root, "format/examples/nothing/valid/a.yaml"), "a: 1\n");
  const { problems } = corpusOf(root, model);
  assert.ok(problems.some((problem) => /format\/vectors\/unknown: tools\/types does not know these vectors/.test(problem)), problems.join("\n"));
  assert.ok(problems.some((problem) => problem.includes(`task/valid/${task}: breaks the YAML rules`)), problems.join("\n"));
  assert.ok(problems.some((problem) => problem.includes("manifest/valid/extra.yaml: does not pass the schema of manifest")), problems.join("\n"));
  assert.ok(problems.some((problem) => problem.includes(`${module}: its canonical view cannot be built`)), problems.join("\n"));
  assert.ok(problems.some((problem) => problem.includes("nothing/valid/a.yaml: no schema of nothing compiles to a type")), problems.join("\n"));

  const script = path.join(spec, "tools", "types", "corpus.mjs");
  const usage = spawnSync(process.execPath, [script], { encoding: "utf8" });
  assert.equal(usage.status, 2);
  const file = path.join(root, "corpus.json");
  const written = spawnSync(process.execPath, [script, file], { encoding: "utf8" });
  assert.equal(written.status, 0, written.stderr);
  assert.match(written.stdout, /^corpus: \d+ cases\n$/);
  assert.ok(JSON.parse(fs.readFileSync(file, "utf8")).length > 0);
});
