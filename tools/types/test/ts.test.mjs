const here = path.dirname(fileURLToPath(import.meta.url));
const spec = path.join(here, "..", "..", "..");
const TSC = path.join(spec, "tools", "node_modules", ".bin", "tsc");

test("a struct is an interface of readonly fields, required when the object always holds them", () => {
  const files = tsFiles(smallModel(), "0.1");
  const base = files.get(`${TYPES_DIR}/index.d.ts`);
  assert.match(base, /^\/\/ Code generated by tools\/types from format\/schemas; DO NOT EDIT\.\n\n\/\*\*\n \* The types of the module format, major version 0, generated from the schemas of version 0\.1/);
  assert.match(base, /\n \* @packageDocumentation\n \*\/\n/);
  assert.match(base, /\/\/ The types of part\.schema\.json\.\n\n\/\*\*\n \* Part is the type of part\.schema\.json\.\n \*\n \* A part\.\n \*\/\nexport interface Part \{\n/);
  assert.match(base, /  \/\*\*\n   \* Its ID\.\n   \*\/\n  readonly id: PartID;\n  readonly kind: PartKind;\n/);
  assert.match(base, /  \/\*\*\n   \* @defaultValue 50\n   \*\/\n  readonly step\?: number;\n/);
  assert.match(base, /  readonly pieces\?: readonly Piece\[\];\n  readonly tiers\?: Tiers;\n  readonly note: string \| null;\n  readonly other\?: OtherPiece;\n  readonly shelf\?: Shelf;\n\}/);
  assert.match(base, /  readonly size: number;\n  readonly on\?: boolean;\n/);
  // An enumeration is a union of its values; any other name is an alias, a struct's too.
  assert.match(base, /export type PartKind = "handwriting_sheet" \| "module-index\.one";\n/);
  assert.match(base, /export type PartID = LocalID;\n/);
  assert.match(base, /export type LocalID = string;\n/);
  assert.match(base, /export type Grade = number;\n/);
  assert.match(base, /export type Tiers = Readonly<Record<PartID, number>>;\n/);
  assert.match(base, /export type OtherPiece = Piece;\n/);
  assert.equal(base.includes("import"), false);
});

test("an open view holds its open fields, by the open views of structs and formatv0's other types", () => {
  const open = tsFiles(smallModel(), "0.1").get(`${OPEN_DIR}/index.d.ts`);
  assert.match(open, /\n \* @packageDocumentation\n \*\/\n\nimport type \* as formatv0 from "\.\.\/index\.js";\n/);
  assert.match(open, /\* Part is the open view of formatv0\.Part, the type of part\.schema\.json: its fields marked x-open\./);
  assert.match(open, /  readonly id: formatv0\.PartID;\n  readonly kind: formatv0\.PartKind;\n/);
  assert.match(open, /  readonly pieces\?: readonly Piece\[\];\n  readonly note: string \| null;\n  readonly shelf\?: Readonly<Record<formatv0\.PartID, Piece>>;\n\}/);
  // A view without a field takes no object with one: an empty interface would.
  assert.match(open, /export type Piece = \{ readonly \[field: string\]: never \};\n/);
  assert.match(open, /export type Empty = \{ readonly \[field: string\]: never \};\n/);

  // Views that use nothing of formatv0 import nothing.
  const lone = smallModel();
  lone.open = new Map([["Empty", { name: "Empty", fields: [] }]]);
  assert.equal(tsFiles(lone, "0.1").get(`${OPEN_DIR}/index.d.ts`).includes("import"), false);
});

test("names, lists of unions, and what the TypeScript of the model cannot hold", () => {
  const model = smallModel();
  model.types.get("Piece").fields.push(fieldOf("a-b", { list: { nullable: { primitive: "string" } } }), fieldOf("grid", { list: { list: { primitive: "integer" } } }));
  const base = tsFiles(model, "0.1").get(`${TYPES_DIR}/index.d.ts`);
  assert.match(base, /  readonly "a-b"\?: readonly \(string \| null\)\[\];\n/);
  assert.match(base, /  readonly grid\?: readonly \(readonly number\[\]\)\[\];\n/);
  // The package's path in the first comment is code, so that no line of it starts with @.
  assert.match(base, /`@altnovatrail\/spec\/formatv0\/open`\.\n \*\n \* @packageDocumentation\n/);

  const keyed = smallModel();
  keyed.types.get("Tiers").type.map.key = { named: "PartKind" };
  assert.throws(() => tsFiles(keyed, "0.1"), /a map is keyed by the enumeration PartKind/);
  // Through another name of the enumeration too.
  const aliased = smallModel();
  aliased.types.set("KindName", { name: "KindName", schema: "part.schema.json", pointer: "/$defs/kind_name", doc: "", kind: "named", type: { named: "PartKind" } });
  aliased.types.get("Tiers").type.map.key = { named: "KindName" };
  assert.throws(() => tsFiles(aliased, "0.1"), /a map is keyed by the enumeration PartKind/);
  const tagged = smallModel();
  tagged.types.get("Piece").fields[0].doc = "Its size, as @altnovatrail names it.";
  assert.throws(() => tsFiles(tagged, "0.1"), /a description holds a word that starts with @/);
  for (const name of ["Readonly", "Record"]) {
    const global = smallModel();
    global.types.set(name, { name, schema: "part.schema.json", pointer: "/$defs/x", doc: "", kind: "integer" });
    assert.throws(() => tsFiles(global, "0.1"), new RegExp(`a type is named ${name}, as a global type of TypeScript`));
  }
  const closing = smallModel();
  closing.types.get("Part").doc = "A part, as in tasks/*/a.yaml.";
  assert.throws(() => tsFiles(closing, "0.1"), /a description holds \*\/, which would end the doc comment/);

  const words = Array.from({ length: 40 }, (_, index) => `word${index}`).join(" ");
  const lines = docOf(`${words}\n\nA second paragraph.`, "  ").split("\n").filter(Boolean);
  assert.equal(lines[0], "  /**");
  assert.equal(lines.at(-1), "   */");
  assert.ok(lines.every((line) => line.length <= 100), lines.join("\n"));
  assert.ok(lines.includes("   *"));
  assert.ok(lines.includes("   * A second paragraph."));
});

// The project of cases against a package of the small model's types, as types-check lays it out.
function project(cases) {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), "types-tsc-"));
  writeProject(cases, path.join(folder, "project"));
  const spec = path.join(folder, "project", "node_modules", "@altnovatrail", "spec");
  for (const [file, text] of tsFiles(smallModel(), "0.1")) {
    const target = path.join(spec, file.slice("types/".length));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
  }
  fs.writeFileSync(path.join(spec, "package.json"), JSON.stringify(manifestOf("0.0.0")));
  return path.join(folder, "project");
}

const tsc = (dir, config) => spawnSync(TSC, ["-p", path.join(dir, config)], { encoding: "utf8" });

test("tsc takes the value of each case under every configuration, and refuses a closed field", () => {
  const part = { id: "a", kind: "handwriting_sheet", note: null, pieces: [{ size: 1.5 }], tiers: { a: 1 }, other: { size: 2, on: true }, shelf: { a: { size: 3 } } };
  const cases = [
    { file: "part.yaml", type: "formatv0.Part", value: part, closed: false },
    { file: "open.yaml", type: "open.Part", value: { id: "a", kind: "module-index.one", note: "n", pieces: [{}], shelf: { a: {} } }, closed: false },
    { file: "closed.yaml", type: "open.Part", value: part, closed: true },
    { file: "empty.yaml", type: "open.Empty", value: { hidden: "h" }, closed: true },
  ];
  const good = project(cases);
  try {
    assert.deepEqual(Object.keys(CONFIGS), ["tsconfig.nodenext.json", "tsconfig.bundler.json"]);
    for (const config of Object.keys(CONFIGS)) {
      const checked = tsc(good, config);
      assert.equal(checked.status, 0, checked.stdout + checked.stderr);
    }
  } finally {
    fs.rmSync(path.dirname(good), { recursive: true, force: true });
  }

  // A value without a field its type requires, a value its enumeration has not, and a closed
  // case whose value has no closed field are each an error.
  const bad = project([
    { file: "missing.yaml", type: "formatv0.Part", value: { id: "a", kind: "handwriting_sheet" }, closed: false },
    { file: "kind.yaml", type: "formatv0.Part", value: { ...part, kind: "other" }, closed: false },
    { file: "open.yaml", type: "open.Part", value: { id: "a", kind: "handwriting_sheet", note: null }, closed: true },
  ]);
  try {
    for (const config of Object.keys(CONFIGS)) {
      const checked = tsc(bad, config);
      assert.notEqual(checked.status, 0, checked.stdout + checked.stderr);
      assert.match(checked.stdout, /corpus\.ts\(7,\d+\): error TS2741: Property 'note' is missing/);
      assert.match(checked.stdout, /corpus\.ts\(10,\d+\): error TS2322: Type '"other"' is not assignable/);
      assert.match(checked.stdout, /corpus\.ts\(13,\d+\): error TS2578: Unused '@ts-expect-error' directive/);
    }
  } finally {
    fs.rmSync(path.dirname(bad), { recursive: true, force: true });
  }
});

test("the project is a declaration of each case on its own line, of the package's types alone", () => {
  const source = sourceOf([
    { file: "a.yaml", type: "formatv0.Part", value: { id: "a" }, closed: false },
    { file: "b.yaml", type: "open.Part", value: { id: "b" }, closed: true },
  ]);
  assert.match(source, /^\/\/ The corpus of tools\/types, 2 cases \(tools\/types\/typescript\.mjs\)\.\n\nimport type \* as formatv0 from "@altnovatrail\/spec\/formatv0";\nimport type \* as open from "@altnovatrail\/spec\/formatv0\/open";\n/);
  assert.match(source, /\n\/\/ a\.yaml\nexport const case0: formatv0\.Part = \{"id":"a"\};\n/);
  assert.match(source, /\n\/\/ b\.yaml, whose closed fields open\.Part has not\n\/\/ @ts-expect-error\nexport const case1: open\.Part = \{"id":"b"\};\n$/);
  for (const type of ["Part", "other.Part", "formatv0.a.Part"]) {
    assert.throws(() => sourceOf([{ file: "c.yaml", type, value: {}, closed: false }]), /c\.yaml: the type .* is of no package of @altnovatrail\/spec/);
  }

  const folder = fs.mkdtempSync(path.join(os.tmpdir(), "types-project-"));
  try {
    const script = path.join(spec, "tools", "types", "typescript.mjs");
    const corpus = path.join(folder, "corpus.json");
    fs.writeFileSync(corpus, JSON.stringify([{ file: "a.yaml", type: "formatv0.Part", value: {}, closed: false }]));
    const written = spawnSync(process.execPath, [script, corpus, path.join(folder, "project")], { encoding: "utf8" });
    assert.equal(written.status, 0, written.stderr);
    assert.equal(written.stdout, "typescript: 1 cases, 2 configurations\n");
    assert.deepEqual(fs.readdirSync(path.join(folder, "project")).sort(), ["corpus.ts", "package.json", "tsconfig.bundler.json", "tsconfig.nodenext.json"]);
    const config = JSON.parse(fs.readFileSync(path.join(folder, "project", "tsconfig.nodenext.json"), "utf8"));
    assert.equal(config.compilerOptions.strict, true);
    assert.equal(config.compilerOptions.skipLibCheck, false);
    assert.deepEqual(config.files, ["corpus.ts"]);
    const again = spawnSync(process.execPath, [script, corpus, path.join(folder, "project")], { encoding: "utf8" });
    assert.equal(again.status, 1);
    assert.match(again.stderr, /^typescript: .*project is there already/);
    const usage = spawnSync(process.execPath, [script], { encoding: "utf8" });
    assert.equal(usage.status, 2);
    assert.match(usage.stderr, /^usage: node tools\/types\/typescript\.mjs <corpus\.json> <folder>/);
  } finally {
    fs.rmSync(folder, { recursive: true, force: true });
  }
});
