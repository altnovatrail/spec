// The Go of the model (R72): the package formatv0, with a type for each type of the model, and
// its subpackage open, with the open view of each struct that the open view of a part reaches, by
// the same name. A struct's field that the object always holds is a value; any other is a
// pointer, or a slice or a map, with omitzero, so that a field left out and a field of zero value
// stay apart, and a value read and written again is the same JSON (RUN.md, T45). A string, an
// integer, a list or a map under a name of its own is a type of its own: a skill's ID is no task's.
// A $ref that narrows a struct is another name of the same struct: a check of an answer slot
// written by hand is a check. The types hold no code: what is valid, the schema decides. The
// admission table's types are the package admissionv0, by the same rules, with no open view (R96),
// the deployment configuration's the package deploymentv1, whose file keeps the names of its
// fields in camelCase, as JSON tags (R85), and the legal texts' the package legalv1 (R130).

import { byCodeUnits } from "../shared.mjs";
import { openRefOf, pascalOf, placeOf } from "./model.mjs";

export const MODULE = "github.com/altnovatrail/spec";
export const PACKAGE = "formatv0";
export const OPEN = "open";
// Where the files go, from the root of the repository.
export const TYPES_DIR = `types/${PACKAGE}`;
export const OPEN_DIR = `${TYPES_DIR}/${OPEN}`;
export const REGISTRY = "tools/types/roundtrip/registry.go";
// The package of the admission table's types, beside formatv0's.
export const ADMISSION_PACKAGE = "admissionv0";
export const ADMISSION_DIR = `types/${ADMISSION_PACKAGE}`;
// The package of the deployment configuration's types, of its version 1, beside them.
export const DEPLOYMENT_PACKAGE = "deploymentv1";
export const DEPLOYMENT_DIR = `types/${DEPLOYMENT_PACKAGE}`;
// The package of the legal texts' types, of the part's version 1, beside them.
export const LEGAL_PACKAGE = "legalv1";
export const LEGAL_DIR = `types/${LEGAL_PACKAGE}`;

const HEADER = "// Code generated by tools/types from format/schemas; DO NOT EDIT.";
const ADMISSION_HEADER = "// Code generated by tools/types from admission/schemas; DO NOT EDIT.";
const DEPLOYMENT_HEADER = "// Code generated by tools/types from deployment/schemas; DO NOT EDIT.";
const LEGAL_HEADER = "// Code generated by tools/types from legal/schemas; DO NOT EDIT.";
const WIDTH = 100;
const PRIMITIVE_GO = { string: "string", integer: "int64", number: "float64", boolean: "bool" };

// The files of the model's Go, by their paths from the root of the repository: the source of
// each, as gofmt leaves it but for the alignment of a struct's fields, which gofmt does. version is
// the format's, which the packages name. admission, when it is given, is the admission table's
// { model, version }: its package goes beside, and the registry names its types too; and so do
// deployment, the deployment configuration's, and legal, the legal texts'.
export function goFiles(model, version, admission = null, deployment = null, legal = null) {
  const files = new Map();
  files.set(`${TYPES_DIR}/doc.go`, packageDoc(PACKAGE, formatDoc(version)));
  for (const [file, body] of bodiesOf(model)) files.set(`${TYPES_DIR}/${file}`, `${HEADER}\n\npackage ${PACKAGE}\n\n${body}`);
  files.set(`${OPEN_DIR}/doc.go`, packageDoc(OPEN, openDoc(version)));
  const views = [...model.open.values()].map((view) => ({ view, type: model.types.get(view.name) }));
  for (const [schema, list] of groupBy(views, ({ type }) => type.schema)) {
    const uses = { base: false };
    const body = list.map(({ view, type }) => openDeclarationOf(view, type, model, uses)).join("\n");
    const imports = uses.base ? `import "${MODULE}/${TYPES_DIR}"\n\n` : "";
    files.set(`${OPEN_DIR}/${fileOf(schema)}`, `${HEADER}\n\npackage ${OPEN}\n\n${imports}${body}`);
  }
  if (admission) {
    files.set(`${ADMISSION_DIR}/doc.go`, packageDoc(ADMISSION_PACKAGE, admissionDoc(admission.version), ADMISSION_HEADER));
    for (const [file, body] of bodiesOf(admission.model)) files.set(`${ADMISSION_DIR}/${file}`, `${ADMISSION_HEADER}\n\npackage ${ADMISSION_PACKAGE}\n\n${body}`);
    checkConstants(admission.model);
  }
  if (deployment) {
    files.set(`${DEPLOYMENT_DIR}/doc.go`, packageDoc(DEPLOYMENT_PACKAGE, deploymentDoc(deployment.version), DEPLOYMENT_HEADER));
    for (const [file, body] of bodiesOf(deployment.model)) files.set(`${DEPLOYMENT_DIR}/${file}`, `${DEPLOYMENT_HEADER}\n\npackage ${DEPLOYMENT_PACKAGE}\n\n${body}`);
    checkConstants(deployment.model);
  }
  if (legal) {
    files.set(`${LEGAL_DIR}/doc.go`, packageDoc(LEGAL_PACKAGE, legalDoc(legal.version), LEGAL_HEADER));
    for (const [file, body] of bodiesOf(legal.model)) files.set(`${LEGAL_DIR}/${file}`, `${LEGAL_HEADER}\n\npackage ${LEGAL_PACKAGE}\n\n${body}`);
    checkConstants(legal.model);
  }
  files.set(REGISTRY, registryOf(model, admission?.model, deployment?.model, legal?.model));
  checkConstants(model);
  return files;
}

// The Go of each schema's types, by the name of its file: with the import of encoding/json when a
// field holds any JSON value, as json.RawMessage.
function bodiesOf(model) {
  return [...groupBy([...model.types.values()], (type) => type.schema)].map(([schema, types]) => {
    const imports = types.some((type) => type.kind === "struct" && type.fields.some((field) => holdsAny(field.type))) ? 'import "encoding/json"\n\n' : "";
    return [fileOf(schema), `${imports}${types.map((type) => declarationOf(type, model)).join("\n")}`];
  });
}

// Whether a type is any JSON value, or a list, a map or a nullable of one.
function holdsAny(ref) {
  if (ref.any) return true;
  if (ref.list) return holdsAny(ref.list);
  if (ref.map) return holdsAny(ref.map.value);
  return ref.nullable ? holdsAny(ref.nullable) : false;
}

function formatDoc(version) {
  return `Package ${PACKAGE} holds the types of the module format, major version 0, generated from the schemas of version ${version} in format/schemas by tools/types (R72 in spec's docs/decisions.md). There is a type for each schema and for each of its $defs, for each object at a place without a name of its own, and for each enumeration of a field. The schemas decide what is valid: a type gives the shape of a value alone, and code that reads a value from elsewhere checks it against its schema first. A field the object always holds is a value; any other is a pointer, a slice or a map, left out when nil, so that a value read and written again is the same JSON. The open view of each part is in the subpackage ${OPEN}.`;
}

function openDoc(version) {
  return `Package ${OPEN} holds the open view of each part of a module (format/README.md, section 6): the struct of each type the open view of a part reaches, by the name it has in ${PACKAGE}, with the fields marked x-open alone, of version ${version}. An open view has no check, no template and no solver; a task's has its givens and its unknown. Strings, integers and enumerations are ${PACKAGE}'s.`;
}

