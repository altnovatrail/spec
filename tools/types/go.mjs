// The Go of the model (R72): the package formatv0, with a type for each type of the model, and
// its subpackage open, with the open view of each struct that the open view of a part reaches, by
// the same name. A struct's field that the object always holds is a value; any other is a
// pointer, or a slice or a map, with omitzero, so that a field left out and a field of zero value
// stay apart, and a value read and written again is the same JSON (RUN.md, T45). A string, an
// integer, a list or a map under a name of its own is a type of its own: a skill's ID is no task's.
// A $ref that narrows a struct is another name of the same struct: a check of an answer slot
// written by hand is a check. The types hold no code: what is valid, the schema decides.

import { byCodeUnits } from "../shared.mjs";
import { openRefOf, pascalOf, placeOf } from "./model.mjs";

export const MODULE = "github.com/altnovatrail/spec";
export const PACKAGE = "formatv0";
export const OPEN = "open";
// Where the files go, from the root of the repository.
export const TYPES_DIR = `types/${PACKAGE}`;
export const OPEN_DIR = `${TYPES_DIR}/${OPEN}`;
export const REGISTRY = "tools/types/roundtrip/registry.go";

const HEADER = "// Code generated by tools/types from format/schemas; DO NOT EDIT.";
const WIDTH = 100;
const PRIMITIVE_GO = { string: "string", integer: "int64", number: "float64", boolean: "bool" };

// The files of the model's Go, by their paths from the root of the repository: the source of
// each, as gofmt leaves it but for the alignment of a struct's fields, which gofmt does. version is
// the format's, which the packages name.
export function goFiles(model, version) {
  const files = new Map();
  const bySchema = groupBy([...model.types.values()], (type) => type.schema);
  files.set(`${TYPES_DIR}/doc.go`, packageDoc(PACKAGE, formatDoc(version)));
  for (const [schema, types] of bySchema) {
    const body = types.map((type) => declarationOf(type, model)).join("\n");
    files.set(`${TYPES_DIR}/${fileOf(schema)}`, `${HEADER}\n\npackage ${PACKAGE}\n\n${body}`);
  }
  files.set(`${OPEN_DIR}/doc.go`, packageDoc(OPEN, openDoc(version)));
  const views = [...model.open.values()].map((view) => ({ view, type: model.types.get(view.name) }));
  for (const [schema, list] of groupBy(views, ({ type }) => type.schema)) {
    const uses = { base: false };
    const body = list.map(({ view, type }) => openDeclarationOf(view, type, model, uses)).join("\n");
    const imports = uses.base ? `import "${MODULE}/${TYPES_DIR}"\n\n` : "";
    files.set(`${OPEN_DIR}/${fileOf(schema)}`, `${HEADER}\n\npackage ${OPEN}\n\n${imports}${body}`);
  }
  files.set(REGISTRY, registryOf(model));
  checkConstants(model);
  return files;
}

function formatDoc(version) {
  return `Package ${PACKAGE} holds the types of the module format, major version 0, generated from the schemas of version ${version} in format/schemas by tools/types (R72 in spec's docs/decisions.md). There is a type for each schema and for each of its $defs, for each object at a place without a name of its own, and for each enumeration of a field. The schemas decide what is valid: a type gives the shape of a value alone, and code that reads a value from elsewhere checks it against its schema first. A field the object always holds is a value; any other is a pointer, a slice or a map, left out when nil, so that a value read and written again is the same JSON. The open view of each part is in the subpackage ${OPEN}.`;
}

function openDoc(version) {
  return `Package ${OPEN} holds the open view of each part of a module (format/README.md, section 6): the struct of each type the open view of a part reaches, by the name it has in ${PACKAGE}, with the fields marked x-open alone, of version ${version}. An open view has no check, no template and no solver; a task's has its givens and its unknown. Strings, integers and enumerations are ${PACKAGE}'s.`;
}

function packageDoc(name, text) {
  return `${HEADER}\n\n${commentOf(text, "")}package ${name}\n`;
}

// The declaration of a type of the model in formatv0.
function declarationOf(type, model) {
  const doc = commentOf(`${type.name} is the type of ${placeOf(type)}.${type.doc ? `\n\n${type.doc}` : ""}`, "");
  switch (type.kind) {
    case "struct":
      return `${doc}type ${type.name} ${structOf(fieldsOf(type.fields, model, (ref) => goOf(ref, (name) => name)))}\n`;
    case "string":
      return `${doc}type ${type.name} string\n${type.values ? constantsOf(type) : ""}`;
    case "integer":
      return `${doc}type ${type.name} int64\n`;
    default: {
      const target = model.types.get(type.type.named);
      // Another name of a struct is the same struct; a string, a list or a map is a type of its own.
      const alias = target?.kind === "struct" ? " =" : "";
      return `${doc}type ${type.name}${alias} ${goOf(type.type, (name) => name)}\n`;
    }
  }
}

// The declaration of an open view in the package open.
function openDeclarationOf(view, type, model, uses) {
  const doc = commentOf(`${view.name} is the open view of ${PACKAGE}.${view.name}, the type of ${placeOf(type)}: its fields marked x-open.${type.doc ? `\n\n${type.doc}` : ""}`, "");
  return `${doc}type ${view.name} ${structOf(fieldsOf(view.fields, model, (ref) => openGoOf(ref, model, uses)))}\n`;
}

// A struct of its fields' lines: struct{} when it has none, as the open view of the trap catalog.
function structOf(fields) {
  return fields ? `struct {\n${fields}}` : "struct{}";
}

function fieldsOf(fields, model, render) {
  return fields
    .map((field) => {
      const notes = [field.doc, field.default === undefined ? "" : `Default: ${JSON.stringify(field.default)}.`].filter(Boolean).join("\n\n");
      const doc = notes ? commentOf(notes, "\t") : "";
      const type = render(field.type);
      if (field.type.nullable && !field.required) throw new Error(`the field ${field.json} may be left out and may be null: the Go of the model knows one of them`);
      const optional = !field.required && !field.type.nullable;
      const pointer = optional && !isCollection(field.type, model) ? "*" : "";
      return `${doc}\t${pascalOf(field.json)} ${pointer}${type} \`json:"${field.json}${optional ? ",omitzero" : ""}"\`\n`;
    })
    .join("");
}

// The values of an enumeration, as constants named after the type and the value.
function constantsOf(type) {
  const lines = type.values.map((value) => `\t${type.name}${pascalOf(value)} ${type.name} = ${JSON.stringify(value)}\n`);
  return `\n// The values of ${type.name}.\nconst (\n${lines.join("")})\n`;
}

// No two constants of a package share a name.
function checkConstants(model) {
  const seen = new Map();
  for (const type of model.types.values()) {
    for (const value of type.kind === "string" ? (type.values ?? []) : []) {
      const name = `${type.name}${pascalOf(value)}`;
      if (model.types.has(name)) throw new Error(`the constant ${name} of ${type.name} is named as a type is`);
      if (seen.has(name)) throw new Error(`the constant ${name} of ${type.name} is named as one of ${seen.get(name)} is`);
      seen.set(name, type.name);
    }
  }
}

// The Go of a type, each named type written as named writes it: by its name in formatv0, and with
// formatv0's name in open. An open view, which openRefOf gives, is open's own.
function goOf(ref, named) {
  if (ref.primitive) return PRIMITIVE_GO[ref.primitive];
  if (ref.view) return ref.view;
  if (ref.named) return named(ref.named);
  if (ref.list) return `[]${goOf(ref.list, named)}`;
  if (ref.map) return `map[${goOf(ref.map.key, named)}]${goOf(ref.map.value, named)}`;
  return `*${goOf(ref.nullable, named)}`;
}

// The Go of a type in open: a struct's open view by its own name, any other named type formatv0's.
function openGoOf(ref, model, uses) {
  return goOf(openRefOf(ref, model.types), (name) => {
    uses.base = true;
    return `${PACKAGE}.${name}`;
  });
}

// Whether a type is a slice or a map, by itself or under a name of its own: then nil leaves it out.
function isCollection(ref, model) {
  if (ref.list || ref.map) return true;
  const type = ref.named ? model.types.get(ref.named) : undefined;
  return type?.kind === "named" && isCollection(type.type, model);
}

// The registry of the roundtrip command: a new value of each root type, by the name its corpus
// gives it, of formatv0 and of open.
function registryOf(model) {
  const entries = [];
  for (const name of model.roots.values()) entries.push([`${PACKAGE}.${name}`, `${PACKAGE}.${name}`]);
  for (const name of model.open.keys()) entries.push([`${OPEN}.${name}`, `${OPEN}.${name}`]);
  entries.sort(([a], [b]) => byCodeUnits(a, b));
  const lines = entries.map(([key, type]) => `\t${JSON.stringify(key)}: func() any { return new(${type}) },\n`).join("");
  return `${HEADER}\n\npackage main\n\nimport (\n\t"${MODULE}/${TYPES_DIR}"\n\t"${MODULE}/${OPEN_DIR}"\n)\n\n// typesByName gives a new value of each type of formatv0 and of open, by its name in the corpus.\nvar typesByName = map[string]func() any{\n${lines}}\n`;
}

// The Go file of a schema: skill-graph.schema.json → skill_graph.go.
function fileOf(schema) {
  return `${schema.slice(0, -".schema.json".length).replaceAll("-", "_")}.go`;
}

// A comment of text, its paragraphs apart by an empty line, each line no wider than WIDTH with
// the indent, a tab counted as four.
export function commentOf(text, indent) {
  return linesOf(text, WIDTH - indent.length * 4 - 3)
    .map((line) => `${indent}//${line ? ` ${line}` : ""}\n`)
    .join("");
}

// The lines of text, each no wider than room: its words, and an empty line between paragraphs.
export function linesOf(text, room) {
  const lines = [];
  text.split("\n\n").forEach((paragraph, index) => {
    if (index > 0) lines.push("");
    let line = "";
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if (line && line.length + 1 + word.length > room) {
        lines.push(line);
        line = word;
      } else line = line ? `${line} ${word}` : word;
    }
    if (line) lines.push(line);
  });
  return lines;
}

// The items of list in groups, by the key keyOf gives each, in the order the keys first come.
export function groupBy(list, keyOf) {
  const groups = new Map();
  for (const item of list) {
    const key = keyOf(item);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(item);
  }
  return groups;
}
